/* =============================================================================
   build-sitemap.js  —  regenerates sitemap.xml from data/content.js
   =============================================================================
   Run automatically by the deploy workflow on every push. It reads the gallery
   and project photos you have added to data/content.js and lists each one as an
   image in the sitemap, so Google Images can find them for local searches.

   YOU DO NOT RUN THIS BY HAND. Just add photos to data/content.js as usual and
   push — the sitemap updates itself. (To preview locally: `node tools/build-sitemap.js`.)
   ============================================================================= */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://limassolfraternite.github.io/';

/* content.js declares `const CONTENT = {...}` (not a module). Evaluate it in an
   isolated function scope and hand back the object. */
function load(file, name) {
  const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
  // eslint-disable-next-line no-new-func
  return new Function(src + '\nreturn typeof ' + name + ' !== "undefined" ? ' + name + ' : null;')();
}

const CONTENT = load('data/content.js', 'CONTENT') || {};

/* pick English (or the plain string, or first available) for image titles */
const en = (v) => {
  if (v == null) return '';
  if (typeof v === 'string') return v;
  return v.en || v.el || v.fr || '';
};
const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&apos;');
const abs = (p) => p.startsWith('http') ? p : SITE + p.replace(/^\//, '');

/* collect images: the social share cover, every gallery photo, every project
   photo — skipping empty placeholders and de-duplicating by URL. */
const seen = new Set();
const images = [];
const add = (src, title) => {
  if (!src) return;
  const url = abs(src);
  if (seen.has(url)) return;
  seen.add(url);
  images.push({ url, title: title || 'Limassol Fraternité Lions Club, Cyprus' });
};

add('assets/img/og-cover.jpg', 'Limassol Fraternité Lions Club, Cyprus');
(CONTENT.gallery || []).forEach((g) => add(g.src, en(g.caption) || en(g.alt)));
(CONTENT.projects || []).forEach((p) => add(p.image, en(p.title) ? en(p.title) + ' — Limassol Fraternité Lions Club' : en(p.alt)));

const imageXml = images.map((im) =>
  '    <image:image>\n' +
  '      <image:loc>' + xml(im.url) + '</image:loc>\n' +
  '      <image:title>' + xml(im.title) + '</image:title>\n' +
  '    </image:image>'
).join('\n');

const out =
`<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/build-sitemap.js — do not edit by hand; add photos in data/content.js -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml"
        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
  <url>
    <loc>${SITE}</loc>
    <xhtml:link rel="alternate" hreflang="en" href="${SITE}?lang=en"/>
    <xhtml:link rel="alternate" hreflang="el" href="${SITE}?lang=el"/>
    <xhtml:link rel="alternate" hreflang="fr" href="${SITE}?lang=fr"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE}"/>
${imageXml}
    <changefreq>weekly</changefreq>
    <priority>1.0</priority>
  </url>
</urlset>
`;

fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), out);
console.log('sitemap.xml written with ' + images.length + ' image(s).');
